-- =====================================================================
-- tab_filial_fap — FAP da filial, um fator por ano (igual ao da empresa,
-- que fica na tab_eventos op1=34). Ano sem FAP na filial = vale o da empresa.
-- Rodar no Supabase -> SQL Editor ANTES de subir a versão que usa a tabela.
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.tab_filial_fap (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente  bigint       NOT NULL,
    id_empresa  bigint       NOT NULL,
    id_filial   bigint       NOT NULL REFERENCES public.tab_filial(id) ON DELETE CASCADE,
    ano         varchar(4)   NOT NULL,
    fator       numeric(6,4) NOT NULL CHECK (fator BETWEEN 0.5 AND 2.0),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (id_filial, ano)
);

-- O app lê e grava com a chave anon, como nas demais tabelas do sistema.
ALTER TABLE public.tab_filial_fap DISABLE ROW LEVEL SECURITY;

-- Filiais já cadastradas recebem os FAP da empresa delas (todos os anos).
INSERT INTO public.tab_filial_fap (id_cliente, id_empresa, id_filial, ano, fator)
SELECT f.id_cliente, f.id_empresa, f.id, ev.campotxt1,
       round(replace(ev.campotxt2, ',', '.')::numeric, 4)
  FROM public.tab_filial f
  JOIN public.tab_eventos ev ON ev.id_empresa = f.id_empresa AND ev.op1 = 34
 WHERE ev.campotxt1 ~ '^\d{4}$'
   AND ev.campotxt2 ~ '^\d+([.,]\d+)?$'
   AND replace(ev.campotxt2, ',', '.')::numeric BETWEEN 0.5 AND 2.0
ON CONFLICT (id_filial, ano) DO NOTHING;

SELECT f.id, f.id_empresa, f.filial_nome, f.gps_fpas, ff.ano, ff.fator
  FROM public.tab_filial f
  LEFT JOIN public.tab_filial_fap ff ON ff.id_filial = f.id
 ORDER BY f.id_empresa, f.filial_nome, ff.ano;

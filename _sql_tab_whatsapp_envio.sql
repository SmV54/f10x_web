-- Contracheque por WhatsApp: uma linha por funcionario em cada remessa.
-- A tela manda um por vez (50 a 80 s entre um e outro) e grava aqui o
-- resultado; o relatorio final e a retomada de remessa interrompida saem
-- desta tabela.
--   situacao: P = pendente, X = enviando, O = enviado, E = erro,
--             S = sem celular valido (nem tenta enviar)
create table if not exists public.tab_whatsapp_envio (
    id            bigint generated by default as identity primary key,
    id_cliente    integer      not null,
    id_empresa    integer      not null,
    remessa       varchar(20)  not null,          -- YYYYMMDDHHMMSS + 4 aleatorios
    anomes        integer      not null,
    anomes_tipo   varchar(1)   not null,
    tipo_doc      varchar(20)  not null default 'CONTRACHEQUE',
    matricula     integer      not null,
    nome          varchar(80),
    celular       varchar(15),
    situacao      char(1)      not null default 'P'
                  check (situacao in ('P','X','O','E','S')),
    msg_erro      text,
    texto_extra   text,
    usuario       varchar(80),
    criado_em     timestamptz  not null default now(),
    enviado_em    timestamptz
);

create index if not exists ix_whatsapp_envio_remessa
    on public.tab_whatsapp_envio (id_empresa, remessa);
create index if not exists ix_whatsapp_envio_folha
    on public.tab_whatsapp_envio (id_empresa, anomes, anomes_tipo);

alter table public.tab_whatsapp_envio disable row level security;
